function f = frankgaowei(X)
% FRANK_FUNCTION 计算Frank测试函数值，支持矩阵输入并返回向量输出
% 输入: X - m×n矩阵（每行代表一个n维点，n≥3）
% 输出: f - m×1向量（每个元素对应X中一行的函数值）
    if isvector(X)
        X = reshape(X, 1, []);
    end
    % 提取各维度变量（向量化操作）
    x = X(1, :);  
    y = X(2, :);  
    z = X(3, :);  
    % 向量化计算函数值（无需循环，直接对向量运算）
    %f = 3/4 * exp(-((9*x - 2).^2 + (9*y - 2).^2 + (9*z - 2).^2)/4) ...
    %    + 3/4 * exp(-((9*x - 1).^2)/49 - ((9*y + 1).^2)/10 - ((9*z + 1).^2)/10) ...
     %   - 1/5 * exp(-((9*x - 4).^2 + (9*y - 7).^2 + (9*z - 5).^2)) ...
      %  + 1/2 * exp(-((9*x - 7).^2 + (9*y - 3).^2 + (9*z - 6).^2)/4);
    f = 3/4 * exp(-((9*x - 2).^2 + (9*y - 2).^2 + (z-2))/4) ...
        + 3/4 * exp(-((9*x - 1).^2)/49 - ((9*y + 1).^2)/10 + ((z).^2)/10) ...
        - 1/5 * exp(-((9*x - 4).^2 + (9*y - 7).^2 + (z).^2)) ...
        + 1/2 * exp(-((9*x - 7).^2 + (9*y - 3).^2 + (z-2))/4);
    % 确保输出为列向量
    f = f(:)';
end